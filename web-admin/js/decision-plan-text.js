export function dpText(lang, key, vars = {}) {
    const value = TEXT[lang]?.[key] ?? TEXT.en[key];
    return typeof value === "function" ? value(vars) : value;
}

export function dpTypeLabel(lang, type) {
    return TYPE_LABELS[lang]?.[type] || TYPE_LABELS.en[type] || String(type || "").replace(/_/g, " ");
}

export function dpSourceLabel(lang, kind) {
    return SOURCE_LABELS[lang]?.[kind] || SOURCE_LABELS[lang]?.other;
}

/** Translates the period labels made by the analytics page. */
export function dpPeriodLabel(lang, label) {
    const text = String(label || "");
    if (lang !== "fil") return text;
    const custom = text.match(/^Custom Range \((\d+) days\)$/);
    if (custom) return `Piling Panahon (${custom[1]} araw)`;
    return {
        "Last 24 Hours": "Huling 24 na Oras",
        "Last 7 Days": "Huling 7 Araw",
        "Last 30 Days": "Huling 30 Araw",
        "Last 90 Days": "Huling 90 Araw",
        "All Historical Data": "Lahat ng Datos",
        "Selected Range": "Napiling Panahon",
    }[text] || text;
}
