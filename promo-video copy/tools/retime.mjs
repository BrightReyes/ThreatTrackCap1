// tools/retime.mjs — Fit each scene to its measured VO line (removes dead air, stops rushed reads).
//
// anim.js stays authored in SOURCE seconds (the TL beats + literals). This tool writes a piecewise-linear
// warp (source → output seconds) into timeline.js, then propagates OUTPUT times to:
//   • index.html  data-start / data-duration of #root and #s1–#s15 (HyperFrames clip visibility)
//   • audio/vo-script.json  seg.start / seg.duration (mix + captions)
//
// Per scene i with source length d, VO offset `off` (source s after the cut) and VO length v:
//   k = max(minK, (v + TAIL) / (d - off))   → output length d·k, VO starts at start' + off·k
// so every line ends ≥ TAIL before the next cut (CLAUDE.md §4.2 needs ≥ 0.25 s).
import fs from "node:fs";
import path from "node:path";
import { ROOT, TIMELINE_PATH, SCENES, loadTL } from "./tl.mjs";

const TAIL = 0.26; // ≥ 0.25 s between a line's end and the next cut (CLAUDE.md §4.2)
const DEFAULT_OFF = 0.03; // stems already carry up to 0.12 s of the natural breath at each end
const DEFAULT_MIN_K = 0.7; // a scene may compress to 70% when the read is faster than the picture
// sync: [sourceTime, word] pairs — that source beat lands on that spoken word (needs audio/vo/words.json).
// A word is matched by text (case/punctuation-insensitive), searching forward from the previous match, so the
// rules survive script edits; a number is a word index. Missing words are reported and skipped.
const SCENE_RULES = {
  s1: { off: 0.2 },
  s5: { sync: () => [[11.4, "report"], [12.1, "track"], [12.8, "respond"]] },
  s6: { minK: 0.9, sync: () => [[14.4, "hold"], [16.35, "your"]] }, // hold starts on "Hold", release on "Your exact location"
  s7: { sync: () => [[20.8, "choose"], [22.6, "snap"], [23.4, "send"]] }, // the three taps + submit
  s10: { minK: 0.6, sync: (S) => [[S.click1, "click"], [S.aiStart, "ai"], [S.hqClick, "headquarters"], [S.subDeploy, "unit"], [S.way, "you"]] },
  s12: { minK: 0.6, sync: (S) => [[S.clickGen, "prepares"], [S.approve, "always"]] },
  s13: { sync: (S) => S.w.map((t, i) => [t, ["your", "your", "valenzuela", "one", "greater", "protected", "a"][i]]) }, // on-screen phrases
  s15: { minK: 1.0, off: (S) => S.shardL - S.start - 0.1, sync: (S) => [[S.shardL, "report"], [S.shardR, "track"], [S.shardT, "respond"], [S.lock, "threattrack"]] }
};
const SYNC_LEAD = 0.06; // picture leads the voice slightly, which reads as "in sync"
const wordsPath = path.join(ROOT, "audio/vo/words.json");
const WORDS = fs.existsSync(wordsPath) ? JSON.parse(fs.readFileSync(wordsPath, "utf8")) : null;
const syncReport = [];

const GEN_START = "// ---- GENERATED by tools/retime.mjs — do not hand-edit below this line ----";
const GEN_END = "// ---- END GENERATED ----";

const raw = fs.readFileSync(TIMELINE_PATH, "utf8");
const sourceSrc = raw.includes(GEN_START) ? raw.slice(0, raw.indexOf(GEN_START)).trimEnd() + "\n" : raw;
const TL = loadTL(sourceSrc); // pure source beats (no previous warp)

const vo = JSON.parse(fs.readFileSync(path.join(ROOT, "audio/vo-script.json"), "utf8"));
const durations = JSON.parse(fs.readFileSync(path.join(ROOT, "audio/vo/durations.json"), "utf8"));

const knots = [];
const out = {};
let cursor = 0;
for (const id of SCENES) {
  const S = TL[id];
  const d = S.end - S.start;
  const rule = SCENE_RULES[id] || {};
  const off = typeof rule.off === "function" ? rule.off(S) : rule.off ?? DEFAULT_OFF;
  const seg = vo.segments.find((s) => s.scene === id);
  const v = seg ? durations[seg.id] : 0;
  if (seg && !(v > 0)) throw new Error(`No measured duration for ${seg.id}; run node tools/generate-vo.mjs`);
  const k = Math.max(rule.minK ?? DEFAULT_MIN_K, seg ? (v + TAIL) / (d - off) : 0);
  knots.push([S.start, +cursor.toFixed(3)]);
  out[id] = { start: +cursor.toFixed(3), duration: +(d * k).toFixed(3), k: +k.toFixed(4), voStart: +(cursor + off * k).toFixed(3), voDur: v };

  // Word-level sync: extra knots so chosen source beats land on chosen spoken words.
  if (rule.sync && seg && WORDS?.[seg.id]) {
    const wl = WORDS[seg.id];
    let pS = S.start, pO = cursor;
    const endO = cursor + d * k;
    const norm = (x) => String(x).toLowerCase().replace(/[^a-z0-9']/g, "");
    let searchFrom = 0;
    for (const [src, ref] of rule.sync(S).sort((a, b) => a[0] - b[0])) {
      const wi = typeof ref === "number" ? ref : wl.findIndex((w, j) => j >= searchFrom && norm(w.w) === norm(ref));
      if (!wl[wi]) { syncReport.push(`${id}: word "${ref}" not found in the line — beat ${src} not synced`); continue; }
      searchFrom = wi + 1;
      const target = out[id].voStart + wl[wi].start - SYNC_LEAD;
      const slope = (target - pO) / (src - pS);
      // keep the warp monotonic and sane (no segment faster than 3× or slower than 0.3×)
      if (src > pS + 0.05 && target > pO + 0.02 && target < endO - 0.3 && slope >= 0.3 && slope <= 3) {
        knots.push([src, +target.toFixed(3)]);
        syncReport.push(`${id}: beat ${src.toFixed(2)} → "${wl[wi].w}"`);
        pS = src; pO = target;
      } else syncReport.push(`${id}: beat ${src.toFixed(2)} → "${wl[wi].w}" SKIPPED (slope ${slope.toFixed(2)})`);
    }
    // the segment after the last sync knot must also be sane
    const tailSlope = (endO - pO) / (S.end - pS);
    if (tailSlope < 0.3 || tailSlope > 3) syncReport.push(`${id}: tail slope ${tailSlope.toFixed(2)} out of range`);
  }
  cursor += d * k;
}
knots.push([TL.s15.end, +cursor.toFixed(3)]);
const outDuration = +cursor.toFixed(3);

// Captions (OUTPUT time). Lines over ~64 chars are split at sentence/clause breaks; each chunk gets
// screen time proportional to its length, so the caption tracks the narrator.
const MAX_CHARS = 64;
function chunk(text) {
  const parts = text.match(/[^.?!]+[.?!]*\s*/g).map((s) => s.trim()).filter(Boolean);
  const out = [];
  for (const p of parts) {
    if (out.length && (out[out.length - 1] + " " + p).length <= MAX_CHARS) out[out.length - 1] += " " + p;
    else if (p.length <= MAX_CHARS) out.push(p);
    else {
      // split long sentence at commas
      let cur = "";
      for (const c of p.split(/(?<=,)\s+/)) {
        if (cur && (cur + " " + c).length > MAX_CHARS) { out.push(cur); cur = c; } else cur = cur ? cur + " " + c : c;
      }
      if (cur) out.push(cur);
    }
  }
  return out;
}
const captions = [];
for (const seg of vo.segments) {
  const o = out[seg.scene];
  const pieces = chunk(seg.text);
  const wl = WORDS?.[seg.id];
  if (wl) {
    // exact: each chunk spans from its first word's start to its last word's end
    let wi = 0;
    for (const p of pieces) {
      const n = p.split(/\s+/).length;
      const a = wl[wi], b = wl[Math.min(wi + n, wl.length) - 1];
      captions.push({ start: +(o.voStart + a.start).toFixed(3), end: +(o.voStart + b.end + 0.15).toFixed(3), text: p });
      wi += n;
    }
    continue;
  }
  const total = pieces.reduce((n, p) => n + p.length, 0);
  let t = o.voStart;
  for (const p of pieces) {
    const d = (o.voDur * p.length) / total;
    captions.push({ start: +t.toFixed(3), end: +(t + d).toFixed(3), text: p });
    t += d;
  }
}

// 1. timeline.js — append generated warp block
const gen = `${GEN_START}
// Output length ${outDuration}s (source ${TL.duration}s). Knots map source → output seconds at each scene cut.
TL.knots = ${JSON.stringify(knots)};
TL.outDuration = ${outDuration};
TL.out = ${JSON.stringify(Object.fromEntries(SCENES.map((id) => [id, { start: out[id].start, duration: out[id].duration }])))};
TL.captions = ${JSON.stringify(captions)};
TL.warp = function (t) {
  const K = TL.knots;
  if (t <= K[0][0]) return t;
  for (let i = 1; i < K.length; i++) {
    if (t <= K[i][0]) {
      const [s0, o0] = K[i - 1], [s1, o1] = K[i];
      return o0 + ((t - s0) * (o1 - o0)) / (s1 - s0);
    }
  }
  const [sl, ol] = K[K.length - 1];
  return ol + (t - sl);
};
// Like warp(), but anything placed shortly before a knot (a scene cut or a word-synced beat) keeps its REAL-time
// lead to that knot instead of being stretched: exits finish right at the cut, fly-ins land right on the word.
TL.EDGE = 0.4;
// max() keeps it monotonic: in stretched spans the real lead wins; in compressed spans plain warp is already closer.
TL.warpEdge = function (t) {
  const w = TL.warp(t);
  for (const [ks, ko] of TL.knots) {
    const lead = ks - t;
    if (lead > 1e-6 && lead <= TL.EDGE) return Math.max(w, ko - lead);
    if (lead > TL.EDGE) break;
  }
  return w;
};
${GEN_END}
`;
fs.writeFileSync(TIMELINE_PATH, sourceSrc + gen);

// 2. index.html — clip windows in output time
const htmlPath = path.join(ROOT, "index.html");
let html = fs.readFileSync(htmlPath, "utf8");
const setAttrs = (id, start, dur) => {
  const re = new RegExp(`(<[^>]*\\bid="${id}"[^>]*?)data-start="[^"]*"([^>]*?)data-duration="[^"]*"`);
  if (!re.test(html)) throw new Error(`index.html: no data-start/data-duration on #${id}`);
  html = html.replace(re, `$1data-start="${start}"$2data-duration="${dur}"`);
};
setAttrs("root", 0, outDuration);
for (const id of SCENES) setAttrs(id, out[id].start, out[id].duration);
fs.writeFileSync(htmlPath, html);

// 3. vo-script.json — output-time placement
for (const seg of vo.segments) {
  seg.start = out[seg.scene].voStart;
  seg.duration = durations[seg.id];
}
fs.writeFileSync(path.join(ROOT, "audio/vo-script.json"), JSON.stringify(vo, null, 2) + "\n");

// Report + non-overlap check
let bad = 0;
console.log(`scene   src→out   k      VO start+dur  gap to next cut`);
for (const [i, id] of SCENES.entries()) {
  const o = out[id];
  const nextCut = i < 14 ? out[SCENES[i + 1]].start : outDuration;
  const gap = nextCut - (o.voStart + o.voDur);
  if (gap < 0.25) bad++;
  const d = TL[id].end - TL[id].start;
  console.log(`${id.padEnd(5)} ${d.toFixed(2).padStart(5)}→${o.duration.toFixed(2).padEnd(6)} ${o.k.toFixed(2)}  ${o.voStart.toFixed(2).padStart(6)}+${o.voDur.toFixed(2)}  ${gap.toFixed(2)}${gap < 0.25 ? "  ✗" : ""}`);
}
if (syncReport.length) console.log("Word sync:\n  " + syncReport.join("\n  "));
else if (!WORDS) console.log("Word sync: skipped (no audio/vo/words.json — ElevenLabs take not generated yet)");
console.log(`Total: ${TL.duration}s → ${outDuration}s`);
if (bad) {
  console.error(`${bad} VO segment(s) violate the 0.25 s gap rule`);
  process.exit(1);
}
